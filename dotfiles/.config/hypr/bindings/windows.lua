local bind = hl.bind
local layout = hl.dsp.layout

bind("SUPER+BracketLeft", layout("consume_or_expel prev"))
bind("SUPER+BracketRight", layout("consume_or_expel next"))
bind("SUPER+C", layout("fit active"))
bind("SUPER+CTRL+C", layout("fit visible"))
bind("SUPER+CTRL+F", layout("fit expand"))
bind("SUPER+CTRL+SHIFT+mouse_down", layout("swapcol r"))
bind("SUPER+CTRL+SHIFT+mouse_up", layout("swapcol l"))
bind("SUPER+CTRL+mouse_left", layout("swapcol l"))
bind("SUPER+CTRL+mouse_right", layout("swapcol r"))
bind("SUPER+Down", hl.dsp.focus({ direction = "down" }))
bind("SUPER+Equal", layout("colresize +0.1"), { repeating = true })
bind("SUPER+F", hl.dsp.window.fullscreen({ mode = 1 }))
bind("SUPER+H", layout("focus l"))
bind("SUPER+J", hl.dsp.focus({ direction = "down" }))
bind("SUPER+K", hl.dsp.focus({ direction = "up" }))
bind("SUPER+L", layout("focus r"))
bind("SUPER+Left", layout("focus l"))
bind("SUPER+Minus", layout("colresize -0.1"), { repeating = true })
bind("SUPER+Period", layout("expel"))
bind("SUPER+Q", hl.dsp.window.close())
bind("SUPER+R", layout("colresize +conf"))
bind("SUPER+Right", layout("focus r"))
bind("SUPER+SHIFT+Down", hl.dsp.window.swap({ direction = "down" }))
bind("SUPER+SHIFT+Equal", function() local m = hl.get_active_monitor(); if m then hl.dispatch(hl.dsp.window.resize({ x = 0, y = m.height / m.scale * 0.1, relative = true })) end end, { repeating = true })
bind("SUPER+SHIFT+F", hl.dsp.window.fullscreen({ mode = 0 }))
bind("SUPER+SHIFT+H", layout("swapcol l"))
bind("SUPER+SHIFT+J", hl.dsp.window.swap({ direction = "down" }))
bind("SUPER+SHIFT+K", hl.dsp.window.swap({ direction = "up" }))
bind("SUPER+SHIFT+L", layout("swapcol r"))
bind("SUPER+SHIFT+Left", layout("swapcol l"))
bind("SUPER+SHIFT+Minus", function() local m = hl.get_active_monitor(); if m then hl.dispatch(hl.dsp.window.resize({ x = 0, y = -m.height / m.scale * 0.1, relative = true })) end end, { repeating = true })
bind("SUPER+SHIFT+Right", layout("swapcol r"))
bind("SUPER+SHIFT+T", hl.dsp.window.float({ action = "toggle" }))
bind("SUPER+SHIFT+Up", hl.dsp.window.swap({ direction = "up" }))
bind("SUPER+SHIFT+V", function()
    local w = hl.get_active_window()
    if w then hl.dispatch(hl.dsp.window.cycle_next({ floating = not w.floating, tiled = w.floating })) end
end)
bind("SUPER+SHIFT+mouse_down", layout("focus r"))
bind("SUPER+SHIFT+mouse_up", layout("focus l"))
bind("SUPER+Up", hl.dsp.focus({ direction = "up" }))
bind("SUPER+mouse_left", layout("focus l"))
bind("SUPER+mouse_right", layout("focus r"))
